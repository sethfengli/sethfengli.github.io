export function verseOfTheMoment(): Verse {
  const now = new Date()
  const dayIdx = Math.floor(now.getTime() / 86_400_000)
  const slot = (dayIdx + now.getHours()) % VERSES.length
  return VERSES[Math.abs(slot)]
}
