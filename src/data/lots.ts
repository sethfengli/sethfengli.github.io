/** 依等级取配色（用于签面与收藏列表） */
export function levelClass(level: LotLevel): string {
  switch (level) {
    case '上上':
      return 'bg-tibetan-600 text-rice-50'
    case '上吉':
      return 'bg-gold-500 text-ink-900'
    case '中吉':
      return 'bg-sandalwood-500 text-rice-50'
    case '中平':
      return 'bg-sandalwood-200 text-sandalwood-800'
    case '中下':
      return 'bg-moon-200 text-moon-700'
    case '下下':
      return 'bg-ink-500 text-rice-50'
  }
}

/** 伪随机但可复现的抽签（按日种子变化，保证同一签当日同一结果不重复出现） */
export function drawLot(excludeIds: number[] = [], salt: string = ''): GuanyinLot {
  const seed = Date.now() + Math.random() * 1e6
  let idx = Math.floor(Math.abs(Math.sin(seed) * 10000)) % LOTS.length
  let guard = 0
  while (excludeIds.includes(LOTS[idx].id) && guard < LOTS.length * 2) {
    idx = (idx + 1) % LOTS.length
    guard++
  }
  void salt
  return LOTS[idx]
}

export interface SavedLot {
  lotId: number
  drawnAt: number
}

const SAVED_KEY = 'hdc.savedLots'

export function loadSavedLots(): SavedLot[] {
  try {
    const raw = localStorage.getItem(SAVED_KEY)
    if (!raw) return []
    const arr = JSON.parse(raw) as SavedLot[]
    return Array.isArray(arr) ? arr.filter((s) => LOTS.some((l) => l.id === s.lotId)) : []
  } catch {
    return []
  }
}

export function saveLot(lotId: number): SavedLot[] {
  const all = loadSavedLots().filter((s) => s.lotId !== lotId)
  all.unshift({ lotId, drawnAt: Date.now() })
  try {
    localStorage.setItem(SAVED_KEY, JSON.stringify(all.slice(0, 60)))
  } catch {
    /* ignore */
  }
  return all
}

export function clearSavedLots() {
  try {
    localStorage.removeItem(SAVED_KEY)
  } catch {
    /* ignore */
  }
}
